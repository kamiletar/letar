/**
 * Шкала глубины нажатия (press feedback) — общая лестница значений для тем приложений.
 *
 * Одна интерактивная поверхность — один шаг шкалы. Чем крупнее поверхность в пикселях,
 * тем мельче относительное проседание: абсолютный сдвиг края должен оставаться
 * сопоставимым, 6% у кнопки `2xs` и 6% у карточки читаются как разное движение.
 *
 * Шаг `md` — значение по умолчанию: кнопка размера `md` и любая интерактивная
 * поверхность, у которой нет собственного размера (карточка, badge-ссылка).
 *
 * ## Почему это не примитивный токен Chakra
 *
 * `TokenCategory` в Chakra v3 — закрытое объединение (`@chakra-ui/react`,
 * `styled-system/types.d.ts`): категории для transform в нём нет. Завести шкалу токенами
 * можно только заняв чужую категорию (`sizes`, `opacity`), и тогда typegen начнёт
 * предлагать `width="press.md"` — контракт темы станет врать. Значения нужны только на
 * этапе сборки (ни dark mode, ни runtime-переопределений у них нет), поэтому шкала живёт
 * обычной константой. По той же причине к ней неприменима ссылка вида `{durations.micro}`:
 * резолвить нечего.
 *
 * ## Почему здесь готовые строки, а не числа
 *
 * Значения хранятся целыми `transform`-строками под `as const`, чтобы у каждого шага был
 * литеральный тип. Функция, возвращающая `string`, ломает `defineLayerStyles`: значение
 * layer style перестаёт совпадать с `LayerStyle` и уезжает во вторую ветку объединения
 * `Recursive<Token<LayerStyle>>` — TS2322 на КАЖДОМ свойстве объекта, включая соседние
 * `transform: 'none'`. Ошибка указывает не на ту строку, где причина.
 *
 * ## Почему шкала общая, а глубина нажатия в `pressableConfig` — своя
 *
 * `pressableConfig.globalCss` задаёт `[data-pressable]` собственный `_active: scale(0.93)`.
 * Это НЕ шаг этой шкалы и намеренно с ней не сведён: обёртка `Pressable` может стоять
 * поверх кнопки, у которой уже есть своя глубина, и два трансформа перемножились бы
 * (0.93 × 0.97 ≈ 0.90) на двух разных кривых. Приложению, у которого глубина живёт в
 * recipes, `pressableConfig.globalCss` разливать не нужно — достаточно `touchAction`
 * и кейфреймов (образец — `apps/domwellbes/src/theme/index.ts`).
 *
 * @example
 * ```ts
 * import { pressScale } from '@letar/ui'
 *
 * _active: { transform: pressScale.sm }
 * _active: { transform: `translateY(1px) ${pressScale.xl}` }
 * ```
 */
export const pressScale = {
  '2xs': 'scale(0.94)',
  xs: 'scale(0.95)',
  sm: 'scale(0.96)',
  md: 'scale(0.97)',
  lg: 'scale(0.98)',
  xl: 'scale(0.985)',
  '2xl': 'scale(0.99)',
} as const

export type PressDepth = keyof typeof pressScale
