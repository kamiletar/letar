/**
 * Валидация загранпаспорта РФ.
 *
 * Формат `99 9999999` — серия (2 цифры) + номер (7 цифр), единое 9-значное число
 * (Приказ МВД от 31.03.2021 № 186, прил. 12, МЧЗ). Формат одинаков у паспорта старого
 * образца и биометрического.
 *
 * Контрольная сумма существует только в машиночитаемой зоне (Модуль 10, веса 731) —
 * по одному номеру она не проверяется.
 *
 * ⚠️ Серию по типу бланка НЕ валидировать (MASK_ENGINE.md §7.1) — три источника дают три
 * разных набора диапазонов, официального перечня в открытом доступе нет.
 */
import { z } from 'zod/v4'
import { isDigitsOfLength } from './checksum'

/**
 * Проверить формат загранпаспорта (9 цифр).
 */
export function validateForeignPassport(value: string): boolean {
  return isDigitsOfLength(value, 9)
}

/**
 * Zod-схема загранпаспорта (серия 2 + номер 7, 9 цифр).
 */
export function foreignPassportSchema() {
  return z
    .string()
    .transform((v) => v.replace(/\D/g, ''))
    .refine((v) => isDigitsOfLength(v, 9), { message: 'Загранпаспорт должен содержать 9 цифр (серия + номер)' })
}
