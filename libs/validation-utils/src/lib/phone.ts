import { z } from 'zod/v4'

/**
 * Схема валидации российского телефона
 * Поддерживает форматы: +79161234567, 89161234567, +7 (916) 123-45-67 и т.д.
 *
 * Используется в: driving-school
 *
 * @example
 * phoneSchema.parse('+79161234567') // '+79161234567'
 * phoneSchema.parse('8 (916) 123-45-67') // '89161234567'
 * phoneSchema.parse('') // '' (пустой номер разрешён)
 */
export const phoneSchema = z
  .string()
  .transform((val) => val.replace(/[\s\-()]/g, '')) // Убираем пробелы, дефисы, скобки
  .refine(
    (val) => {
      if (val === '') {
        return true
      } // Пустой номер разрешён
      // Проверяем российский номер:
      // - с кодом: +79161234567 или 89161234567 (11-12 символов)
      // - без кода: 9161234567 (10 цифр, начинается с 9)
      return /^(\+7|8)?\d{10}$/.test(val)
    },
    { message: 'Введите корректный российский номер телефона' }
  )

/**
 * Схема валидации обязательного российского телефона
 * Не допускает пустое значение
 *
 * @example
 * requiredPhoneSchema.parse('+79161234567') // '+79161234567'
 * requiredPhoneSchema.parse('') // Ошибка: "Введите номер телефона"
 */
export const requiredPhoneSchema = z
  .string()
  .min(1, 'Введите номер телефона')
  .transform((val) => val.replace(/[\s\-()]/g, ''))
  .refine((val) => /^(\+7|8)?\d{10}$/.test(val), {
    message: 'Введите корректный российский номер телефона',
  })
