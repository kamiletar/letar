// Состояние блога
export interface BlogState {
  savedArticles: string[] // slugs сохранённых статей
  readArticles: string[] // slugs прочитанных статей
  bookmarks: Record<string, string[]> // articleSlug -> закладки в статье
}

// Ключ для IndexedDB
const BLOG_STORAGE_KEY = 'premium-rosstil-blog'

// Глобальное состояние
let blogState: BlogState = {
  savedArticles: [],
  readArticles: [],
  bookmarks: {},
}
const listeners: Set<() => void> = new Set()

const notifyListeners = () => {
  listeners.forEach((listener) => listener())
}

// Загрузка из IndexedDB
const loadFromStorage = async (): Promise<void> => {
  try {
    const stored = await get<BlogState>(BLOG_STORAGE_KEY)
    if (stored) {
      blogState = stored
      notifyListeners()
    }
  } catch (error) {
    console.error('Ошибка загрузки блога:', error)
  }
}

// Сохранение в IndexedDB
const saveToStorage = async (): Promise<void> => {
  try {
    await set(BLOG_STORAGE_KEY, blogState)
  } catch (error) {
    console.error('Ошибка сохранения блога:', error)
  }
}

// Инициализация
let initialized = false
const initialize = () => {
  if (!initialized && typeof window !== 'undefined') {
    initialized = true
    loadFromStorage()
  }
}

// Функции для тестирования
export function __resetBlogState() {
  blogState = { savedArticles: [], readArticles: [], bookmarks: {} }
  listeners.clear()
  initialized = false
}

export function __setBlogState(state: Partial<BlogState>) {
  blogState = { ...blogState, ...state }
  listeners.forEach((l) => l())
}

/**
 * Хук для работы с блогом о моде
 */
export function useFashionBlog() {
  const [isLoading, setIsLoading] = useState(true)

  // Подписка на изменения состояния
  const state = useSyncExternalStore(
    (callback) => {
      listeners.add(callback)
      return () => listeners.delete(callback)
    },
    () => blogState,
    () => blogState
  )

  useEffect(() => {
    initialize()
    const timer = setTimeout(() => setIsLoading(false), 100)
    return () => clearTimeout(timer)
  }, [])

  // Получить все статьи
  const getAllArticles = useCallback((): Article[] => {
    return DEMO_ARTICLES.sort((a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime())
  }, [])

  // Получить статью по slug
  const getArticleBySlug = useCallback((slug: string): Article | null => {
    return DEMO_ARTICLES.find((a) => a.slug === slug) || null
  }, [])

  // Получить статьи по категории
  const getArticlesByCategory = useCallback((category: ArticleCategory): Article[] => {
    return DEMO_ARTICLES.filter((a) => a.category === category).sort(
      (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
    )
  }, [])

  // Получить статьи по тегу
  const getArticlesByTag = useCallback((tag: string): Article[] => {
    return DEMO_ARTICLES.filter((a) => a.tags.includes(tag)).sort(
      (a, b) => new Date(b.publishedAt).getTime() - new Date(a.publishedAt).getTime()
    )
  }, [])

  // Поиск статей
  const searchArticles = useCallback((query: string): Article[] => {
    const lowerQuery = query.toLowerCase()
    return DEMO_ARTICLES.filter(
      (a) =>
        a.title.toLowerCase().includes(lowerQuery) ||
        a.excerpt.toLowerCase().includes(lowerQuery) ||
        a.tags.some((t) => t.toLowerCase().includes(lowerQuery))
    )
  }, [])

  // Сохранить статью для оффлайн
  const saveArticle = useCallback(
    async (slug: string): Promise<void> => {
      if (!state.savedArticles.includes(slug)) {
        blogState = {
          ...blogState,
          savedArticles: [...blogState.savedArticles, slug],
        }
        notifyListeners()
        await saveToStorage()
      }
    },
    [state.savedArticles]
  )

  // Удалить из сохранённых
  const unsaveArticle = useCallback(async (slug: string): Promise<void> => {
    blogState = {
      ...blogState,
      savedArticles: blogState.savedArticles.filter((s) => s !== slug),
    }
    notifyListeners()
    await saveToStorage()
  }, [])

  // Проверить сохранена ли статья
  const isArticleSaved = useCallback(
    (slug: string): boolean => {
      return state.savedArticles.includes(slug)
    },
    [state.savedArticles]
  )

  // Получить сохранённые статьи
  const getSavedArticles = useCallback((): Article[] => {
    return DEMO_ARTICLES.filter((a) => state.savedArticles.includes(a.slug))
  }, [state.savedArticles])

  // Отметить статью как прочитанную
  const markAsRead = useCallback(
    async (slug: string): Promise<void> => {
      if (!state.readArticles.includes(slug)) {
        blogState = {
          ...blogState,
          readArticles: [...blogState.readArticles, slug],
        }
        notifyListeners()
        await saveToStorage()
      }
    },
    [state.readArticles]
  )

  // Проверить прочитана ли статья
  const isArticleRead = useCallback(
    (slug: string): boolean => {
      return state.readArticles.includes(slug)
    },
    [state.readArticles]
  )

  // Получить все теги
  const getAllTags = useCallback((): string[] => {
    const tags = new Set<string>()
    DEMO_ARTICLES.forEach((a) => a.tags.forEach((t) => tags.add(t)))
    return Array.from(tags).sort()
  }, [])

  // Получить похожие статьи
  const getRelatedArticles = useCallback(
    (slug: string, limit = 3): Article[] => {
      const article = getArticleBySlug(slug)
      if (!article) {
        return []
      }

      // Находим статьи с похожими тегами или категорией
      const scored = DEMO_ARTICLES.filter((a) => a.slug !== slug)
        .map((a) => {
          let score = 0
          if (a.category === article.category) {
            score += 2
          }
          const commonTags = a.tags.filter((t) => article.tags.includes(t))
          score += commonTags.length
          return { article: a, score }
        })
        .filter((s) => s.score > 0)
        .sort((a, b) => b.score - a.score)
        .slice(0, limit)

      return scored.map((s) => s.article)
    },
    [getArticleBySlug]
  )

  return {
    articles: getAllArticles(),
    savedArticles: getSavedArticles(),
    savedCount: state.savedArticles.length,
    isLoading,
    getAllArticles,
    getArticleBySlug,
    getArticlesByCategory,
    getArticlesByTag,
    searchArticles,
    saveArticle,
    unsaveArticle,
    isArticleSaved,
    getSavedArticles,
    markAsRead,
    isArticleRead,
    getAllTags,
    getRelatedArticles,
    categoryConfig: CATEGORY_CONFIG,
  }
}
