/**
 * Единственный источник истины по «размерным» числам теста: сколько шкал в ядре
 * и сколько вопросов в банке.
 *
 * Зачем отдельный модуль. Эти два числа встречались в тринадцати местах —
 * в метаданных обеих локалей, на `/for-professionals`, в презентации, в блоке
 * экспериментальных шкал, в dev-страницах. При ревизии 2026-07-28 обнаружилось,
 * что они уже разошлись: банк вырос до 2126 вопросов (этап 5.5), а тексты
 * продолжали обещать 2096. Ровно это и повторилось бы при добавлении 23-й шкалы.
 *
 * ⚠️ Почему `TOTAL_QUESTIONS` — литерал, а не `Object.keys(maxScores).length`.
 * Справочник максимумов весит 462 КБ, и value-импорт ради одного числа утащил бы
 * его в клиентский бандл каждой страницы, которая упоминает размер теста
 * (см. [client-bundle-data-leaks](/.claude/docs/client-bundle-data-leaks.md)).
 * Поэтому число живёт здесь литералом, а от рассинхрона защищает unit-тест
 * `bank-stats.test.ts`, который сверяет его с реальным справочником.
 *
 * ⚠️ Формы слов в текстах («22 шкалы», «из 22 шкал», «по 22 шкалам») подставляются
 * вокруг числа как статические строки. Для 22–24 русские формы совпадают, поэтому
 * подстановки достаточно. Если ядро когда-нибудь опустится до 21 или дорастёт
 * до 25, формы придётся пересмотреть вручную.
 */
import { ALL_SCALE_CODES, EXPERIMENTAL_SCALES } from './personality-types'

/** Число шкал ядра — то, что называется «22 шкалы» в публичных текстах */
export const CORE_SCALE_COUNT = ALL_SCALE_CODES.length

/** Число экспериментальных шкал вне ядра (только кабинет психолога, «бета») */
export const EXPERIMENTAL_SCALE_COUNT = EXPERIMENTAL_SCALES.length

/**
 * Число вопросов в банке. Сверяется с `max-scores-per-question.json` тестом —
 * при вливании нового батча обновить здесь (тест упадёт и напомнит).
 */
export const TOTAL_QUESTIONS = 2126
