/**
 * Seed-скрипт: создаёт начальную новость «Мы запустили сайт».
 * Запуск: nx db:seed grandslamcup
 * Или напрямую: npx tsx prisma/seed.ts
 *
 * Идемпотентен — при повторном запуске не дублирует данные.
 */

import { PrismaClient } from '../src/generated/prisma'

const prisma = new PrismaClient()

async function main() {
  // Находим первого ADMIN-пользователя как автора новости
  const admin = await prisma.user.findFirst({
    where: { roles: { has: 'ADMIN' } },
    select: { id: true, name: true },
  })

  if (!admin) {
    console.warn('Нет ADMIN-пользователя — создайте его через /sign-in и назначьте роль ADMIN')
    return
  }

  // Создаём новость о запуске (upsert — безопасно для повторных запусков)
  const post = await prisma.newsPost.upsert({
    where: { slug: 'my-zapustili-sajt' },
    update: {},
    create: {
      slug: 'my-zapustili-sajt',
      title: 'Мы запустили сайт!',
      excerpt:
        'Кубок Большого Слэма теперь онлайн — расписание, составы, результаты и прямые трансляции счёта с телефона судьи.',
      content: `# Мы запустили сайт!

Привет, поэты, тренеры и болельщики!

Мы рады сообщить, что платформа **Кубка Большого Слэма** официально запущена.

## Что уже работает

- 📅 **Расписание матчей** с возможностью добавить в Google / Apple Календарь
- 🏆 **Турнирная таблица** в реальном времени
- 👥 **Профили команд** — составы, тренеры, история матчей
- 🎤 **Профили поэтов** — биография, статистика выступлений, стихи
- 📊 **Live-скоринг** — баллы обновляются по ходу матча
- 🗳️ **Зрительское голосование** — голосуйте за любимых поэтов прямо со смартфона
- 📺 **Экран проектора** — огромный счёт на большой экран зала

## Как войти

Нажмите **Войти** в правом верхнем углу и авторизуйтесь через Ключницу. После входа тренеры увидят кабинет команды, поэты — личный профиль.

## Что дальше

Мы активно развиваем платформу. В планах — чаты, видеозаписи матчей и мобильное приложение.

Следите за обновлениями и добро пожаловать в Кубок Большого Слэма!`,
      published: true,
      publishedAt: new Date('2025-09-01'),
      authorId: admin.id,
    },
  })

  console.log(`✅ Новость создана: "${post.title}" (slug: ${post.slug})`)
  console.log(`   Автор: ${admin.name ?? admin.id}`)
}

main()
  .catch((e) => {
    console.error('Seed failed:', e)
    process.exit(1)
  })
  .finally(() => prisma.$disconnect())
