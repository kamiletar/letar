/** Нормализация названия команды */
export function normalizeTeamName(name: string): string | null {
  if (!name) {
    return null
  }
  const trimmed = name.trim()
  if (TEAM_ALIASES[trimmed] !== undefined) {
    return TEAM_ALIASES[trimmed] || null // пустая строка → null (для "ничья")
  }
  if (ALL_TEAMS.has(trimmed)) {
    return trimmed
  }
  for (const team of ALL_TEAMS) {
    if (team.toLowerCase() === trimmed.toLowerCase()) {
      return team
    }
  }
  return trimmed
}

