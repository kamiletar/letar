/** Нормализация названия площадки */
export function normalizeVenueName(name: string): string {
  let n = name.trim()
  if (VENUE_ALIASES[n]) {
    return VENUE_ALIASES[n]
  }

  // Убираем обёртки "Бар «X»"
  n = n
    .replace(
      /^(?:Бар|Клуб|Ночной клуб|Кафе|Ресторан|Рестобар|Рюмочная|Магазин|Кабак|Бильярдный клуб)\s*[«""]([^»""]+)[»""]\s*$/i,
      '$1',
    )
    .trim()

  if (VENUE_ALIASES[n]) {
    return VENUE_ALIASES[n]
  }

  // Убираем простой префикс "Бар "
  const withoutBarPrefix = n.replace(/^Бар\s+/i, '').trim()
  if (withoutBarPrefix !== n && withoutBarPrefix.length >= 2) {
    if (VENUE_ALIASES[withoutBarPrefix]) {
      return VENUE_ALIASES[withoutBarPrefix]
    }
    n = withoutBarPrefix
  }

  return n
}
