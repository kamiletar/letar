'use client'

import { toaster } from '@/app/_components/ui/toaster'
import { DrivingSchoolForm } from '@/driving-school-form'
import { Button, Stack } from '@chakra-ui/react'
import type { LegalDocumentType } from '@letar/driving-school-db/prisma'
import { useRouter } from 'next/navigation'
import { z } from 'zod/v4'
import { createDocumentVersion } from '../_actions/create-version.action'

interface CreateVersionFormProps {
  documentType: LegalDocumentType
  suggestedVersion: string
  currentContent?: string
}

// Схема для формы (без documentType, он передаётся как prop)
const FormSchema = z
  .object({
    version: z
      .string()
      .min(1, 'Укажите версию')
      .regex(/^\d+\.\d+\.\d+$/, 'Версия должна быть в формате X.Y.Z (например, 1.0.0)'),
    summary: z.string().optional(),
    content: z.string().min(100, 'Содержимое документа должно быть не менее 100 символов'),
  })
  .strip()

export function CreateVersionForm({ documentType, suggestedVersion, currentContent }: CreateVersionFormProps) {
  const router = useRouter()

  return (
    <DrivingSchoolForm
      schema={FormSchema}
      initialValue={{
        version: suggestedVersion,
        summary: '',
        content: currentContent || getDefaultContent(documentType),
      }}
      onSubmit={async (value) => {
        const result = await createDocumentVersion({
          documentType,
          version: value.version,
          content: value.content,
          summary: value.summary || undefined,
        })

        if (!result.success) {
          switch (result.error) {
            case 'VERSION_EXISTS':
              toaster.error({ title: 'Версия уже существует', description: 'Укажите другой номер версии' })
              break
            case 'UNAUTHORIZED':
              toaster.error({ title: 'Нет доступа', description: 'Только владелец может редактировать документы' })
              break
            default:
              toaster.error({ title: 'Ошибка', description: 'Не удалось создать версию документа' })
          }
          return
        }

        toaster.success({ title: 'Версия создана', description: `Версия ${value.version} успешно опубликована` })
        router.push('/owner/legal')
      }}
    >
      <Stack gap={6}>
        {/* Версия */}
        <DrivingSchoolForm.Field.String
          name="version"
          label="Номер версии"
          placeholder="1.0.0"
          helperText="Формат: X.Y.Z (major.minor.patch)"
          required
        />

        {/* Описание изменений */}
        <DrivingSchoolForm.Field.String
          name="summary"
          label="Описание изменений (опционально)"
          placeholder="Например: Добавлен раздел о возврате средств"
        />

        {/* Содержимое документа */}
        <DrivingSchoolForm.Field.Textarea
          name="content"
          label="Содержимое документа"
          placeholder="Текст документа..."
          rows={20}
          helperText="Поддерживается базовое форматирование: **жирный**, *курсив*, # заголовки, - списки"
          required
        />

        {/* Кнопки */}
        <Stack direction="row" gap={4} justify="flex-end">
          <Button variant="outline" onClick={() => router.back()}>
            Отмена
          </Button>
          <DrivingSchoolForm.Button.Submit colorPalette="brand">Опубликовать версию</DrivingSchoolForm.Button.Submit>
        </Stack>
      </Stack>
    </DrivingSchoolForm>
  )
}

