import { z } from 'zod/v4'

/**
 * Общие схемы валидации, используемые в нескольких формах.
 * Централизованное место для переиспользуемых схем.
 */

// =============================================================================
// Email
// =============================================================================

/**
 * Схема валидации email.
 * Используется в: login, register, contact-message.
 */
export const emailSchema = z.email('Введите корректный email')

// =============================================================================
// Slug
// =============================================================================

/**
 * Схема валидации slug (URL-friendly идентификатор).
 * Только латиница в нижнем регистре, цифры и дефис.
 * Используется в: mandala, product, content-page.
 */
export const slugSchema = z
  .string()
  .min(1, 'Slug обязателен')
  .regex(/^[a-z0-9-]+$/, 'Только латиница, цифры и дефис')

// =============================================================================
// Image ID
// =============================================================================

/**
 * Схема Image ID — обязательное поле.
 * Принимает CUID (ID записи в таблице Image).
 */
export const requiredImageIdSchema = z.string().min(1, 'Загрузите изображение')

/**
 * Схема Image ID — опциональное поле.
 * Принимает строку, пустую строку или undefined.
 * Пустая строка трансформируется в null для корректной работы с FK в БД.
 */
export const optionalImageIdSchema = z
  .string()
  .optional()
  .or(z.literal(''))
  .transform((v) => (v === '' ? null : v))

// =============================================================================
// SEO поля
// =============================================================================

/**
 * Схема для опциональных SEO полей (metaTitle, metaDescription, metaKeywords).
 * Может быть пустой строкой или undefined.
 */
export const optionalSeoStringSchema = z.string().optional().or(z.literal(''))
