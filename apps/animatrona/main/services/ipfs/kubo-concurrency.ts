/**
 * Глобальный лимит конкурентности для запросов к демону Kubo (pin.add / add файлов).
 *
 * Без него батч-импорт (десятки файлов на эпизод × десятки эпизодов) шлёт в Kubo
 * неограниченное число одновременных pin.add/add-запросов — все места вызова
 * (uploadManyToIpfs, дорожки субтитров/аудио, скриншоты, спрайты, постеры, pin())
 * суммируются, поэтому лимитировать нужно один раз здесь, а не в каждом месте
 * по отдельности — иначе локальные лимиты просто сложатся и всё равно перегрузят демон.
 *
 * concurrency=4 — по аналогии с уже существующими значениями в этом приложении:
 * createConcurrencyLimiter(2) для демукса (CPU/IO-тяжёлая операция ffmpeg) и батчи
 * по 3 в cid-recovery.ts. IPFS pin/add — сетевой RPC-вызов к локальному демону, дешевле
 * демукса, поэтому лимит чуть выше, но не безграничный.
 */
import { createConcurrencyLimiter } from '../../utils/concurrency-limiter'

export const kuboLimiter = createConcurrencyLimiter(4)
